    #[test]
    fn weakening_or_archiving_negative_evidence_removes_reminder_effect() {
        let engine = ProactiveEngine::default();
        let context = ProactivePersonalContext::default();
        let evidence_store = EvidenceStore::new_in_memory().unwrap();

        let proposal = rejected_pending_proposal();
        let evidence = engine
            .record_rejected_reminder_proposal(&evidence_store, &proposal)
            .unwrap()
            .unwrap();
        evidence_store
            .weaken_evidence(&evidence.id, 0.4, Some("user restored reminder"))
            .unwrap();
        let weakened_suggestions =
            engine.generate_suggestions_with_evidence(&context, 3, 0, Some(4), &evidence_store);
        let pending = weakened_suggestions
            .iter()
            .find(|suggestion| suggestion.category == ProactiveCategory::PendingProposal)
            .unwrap();
        assert_eq!(pending.priority, ProactivePriority::Medium);

        let second = engine
            .record_rejected_reminder_proposal(&evidence_store, &rejected_pending_proposal())
            .unwrap()
            .unwrap();
        evidence_store
            .archive_evidence(&second.id, Some("forget rejected reminder signal"))
            .unwrap();
        let active_records = evidence_store
            .query(EvidenceQuery {
                evidence_type: Some(EvidenceType::RuntimeBehavior),
                status: Some(EvidenceStatus::Archived),
                ..Default::default()
            })
            .unwrap();
        assert_eq!(active_records.len(), 1);

        let archived_suggestions =
            engine.generate_suggestions_with_evidence(&context, 3, 0, Some(4), &evidence_store);
        let pending = archived_suggestions
            .iter()
            .find(|suggestion| suggestion.category == ProactiveCategory::PendingProposal)
            .unwrap();
        assert_eq!(pending.priority, ProactivePriority::Medium);
    }
